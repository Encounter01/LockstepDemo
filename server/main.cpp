/**
 * @file main.cpp
 * @brief 帧同步服务器入口程序
 * @author LockstepDemo
 *
 * ============================================================================
 *                              技术概述
 * ============================================================================
 *
 * 【程序职责】
 * 这是帧同步服务器的入口文件，职责简洁明确：
 * 1. 解析命令行参数
 * 2. 设置信号处理
 * 3. 创建并启动服务器
 * 4. 运行主循环
 * 5. 优雅关闭
 *
 * 【启动流程】
 *
 *    ┌──────────────────────────────────────────────────────┐
 *    │                    main()                            │
 *    ├──────────────────────────────────────────────────────┤
 *    │  1. 解析命令行参数 ───> port                          │
 *    │  2. 注册信号处理器 ───> SIGINT, SIGTERM               │
 *    │  3. 创建服务器实例 ───> LockstepServer(port)          │
 *    │  4. 启动服务器    ───> server.start()                │
 *    │  5. 进入主循环    ───> server.run()  [阻塞]          │
 *    │  6. 退出清理      ───> 析构函数自动调用               │
 *    └──────────────────────────────────────────────────────┘
 *
 * 【使用方法】
 *
 *    # 默认端口启动
 *    ./server.exe
 *
 *    # 指定端口启动
 *    ./server.exe 8888
 *
 *    # 后台运行（Linux）
 *    nohup ./server 9999 > server.log 2>&1 &
 *
 * ============================================================================
 *                              面试要点
 * ============================================================================
 *
 * 【Q1: 为什么使用全局指针g_server？】
 * A: 这是信号处理的经典模式：
 *    1. 信号处理函数只能接受int参数（信号编号）
 *    2. 无法传递额外的上下文（如server对象）
 *    3. 全局变量是最简单的解决方案
 *
 *    更好的方案：
 *    - C++11 lambda + 静态变量
 *    - 使用sigaction替代signal
 *    - 使用self-pipe技巧
 *
 * 【Q2: signal()和sigaction()的区别？】
 * A:
 *    signal():
 *    - POSIX标准，跨平台
 *    - 语义在不同系统上可能不同
 *    - 某些系统上信号处理后会自动重置
 *
 *    sigaction():
 *    - 只在Unix/Linux上可用
 *    - 语义明确，不会自动重置
 *    - 可以设置信号掩码
 *    - 生产环境推荐使用
 *
 * 【Q3: 优雅关闭的重要性？】
 * A:
 *    1. 保存游戏状态/统计数据
 *    2. 通知所有连接的客户端
 *    3. 释放网络资源（关闭socket）
 *    4. 避免端口被占用（TIME_WAIT）
 *    5. 防止数据丢失或损坏
 *
 * ============================================================================
 *                              生产实践
 * ============================================================================
 *
 * 【配置管理】
 * 生产环境不应硬编码端口：
 * 1. 配置文件（JSON/YAML/INI）
 * 2. 环境变量
 * 3. 命令行参数 + 配置文件组合
 * 4. 配置中心（etcd/consul）
 *
 * 【日志系统】
 * 当前使用cout输出，生产环境需要：
 * 1. 日志级别（DEBUG/INFO/WARN/ERROR）
 * 2. 日志轮转（按大小/时间）
 * 3. 异步写入（避免IO阻塞）
 * 4. 结构化日志（JSON格式便于分析）
 * 推荐库：spdlog, glog
 *
 * 【守护进程】
 * Linux生产部署常用方式：
 * 1. systemd服务（推荐）
 * 2. supervisor
 * 3. docker容器
 * 4. 自实现daemon
 *
 * 【监控告警】
 * 1. 进程存活监控
 * 2. 端口监听检查
 * 3. 性能指标上报（Prometheus）
 * 4. 日志告警（ELK Stack）
 */
#include <iostream>
#include <csignal>      // 信号处理
#include "LockstepServer.h"

// ============================================================================
//                          全局变量
// ============================================================================

/**
 * 全局服务器指针
 *
 * 【设计意图】
 * 信号处理函数无法接收额外参数，需要通过全局变量访问服务器实例
 *
 * 【线程安全】
 * - 只在main()中赋值一次
 * - 信号处理函数只读取
 * - 不需要同步机制
 *
 * 【面试Q】有没有更优雅的方式？
 * A: 可以使用以下方案，但增加复杂度：
 *    1. 单例模式：LockstepServer::instance()
 *    2. 静态成员函数作为信号处理器
 *    3. 使用signalfd(Linux)转换为文件事件
 */
lockstep::LockstepServer* g_server = nullptr;

// ============================================================================
//                          信号处理
// ============================================================================

/**
 * @brief 信号处理函数
 * @param signum 收到的信号编号
 *
 * 【处理的信号】
 * - SIGINT (2)  : 用户按Ctrl+C
 * - SIGTERM (15): kill命令默认信号
 *
 * 【执行内容】
 * 调用server.stop()设置running_=false
 * 主循环检测到后会退出
 *
 * 【面试Q】信号处理函数的限制？
 * A: 信号处理函数是异步执行的，有严格限制：
 *    1. 只能调用async-signal-safe的函数
 *    2. 不能使用malloc/free（可能死锁）
 *    3. 不能使用cout（非线程安全）
 *    4. 不能获取锁（可能死锁）
 *
 *    当前实现的cout在信号处理中不是安全的，
 *    但demo中可以接受。生产环境应该：
 *    - 只设置volatile sig_atomic_t标志
 *    - 主循环检测标志后处理
 *
 * 【代码示例：安全的信号处理】
 *
 *    volatile sig_atomic_t g_shutdown = 0;
 *
 *    void handler(int) {
 *        g_shutdown = 1;  // 只设置标志
 *    }
 *
 *    // 主循环中检查
 *    while (running_ && !g_shutdown) {
 *        // ...
 *    }
 */
void signalHandler(int signum) {
    // 【注意】cout在信号处理中不是async-signal-safe的
    // 生产环境应该只设置标志位
    std::cout << "\n[Server] Shutting down..." << std::endl;

    if (g_server) {
        g_server->stop();
    }
}

// ============================================================================
//                          主函数
// ============================================================================

/**
 * @brief 程序入口
 * @param argc 参数个数
 * @param argv 参数数组
 * @return 0=正常退出, 1=启动失败
 *
 * 【参数说明】
 * - argv[0]: 程序名称
 * - argv[1]: 可选的端口号（默认9999）
 *
 * 【返回值】
 * - 0: 正常退出
 * - 1: 启动失败（socket创建或bind失败）
 *
 * 【面试Q】main函数的返回值有什么用？
 * A:
 *    1. Shell脚本可以通过$?获取
 *    2. 用于判断程序是否成功执行
 *    3. systemd等工具根据返回值决定是否重启
 *    4. 惯例：0表示成功，非0表示错误
 */
int main(int argc, char* argv[]) {
    // ========================================================================
    // 步骤1: 解析命令行参数
    // ========================================================================

    /**
     * 【端口选择】
     * - 默认9999：避开常用端口
     * - 用户可通过命令行覆盖
     *
     * 【面试Q】为什么不用1024以下的端口？
     * A:
     *    1. Linux下需要root权限
     *    2. 0-1023是Well-Known Ports（保留端口）
     *    3. 可能与系统服务冲突
     *
     * 【生产改进】
     * - 参数校验（范围1024-65535）
     * - 支持更多配置项（-c config.json）
     * - 使用getopt或更完善的参数解析库
     */
    uint16_t port = 9999;
    if (argc > 1) {
        port = static_cast<uint16_t>(std::atoi(argv[1]));
    }

    // ========================================================================
    // 步骤2: 注册信号处理器
    // ========================================================================

    /**
     * 【注册的信号】
     *
     * SIGINT (2):
     * - 触发方式：Ctrl+C
     * - 用途：交互式中断
     *
     * SIGTERM (15):
     * - 触发方式：kill <pid>
     * - 用途：请求进程终止
     * - systemd默认发送此信号
     *
     * 【未处理的信号】
     * SIGKILL (9):
     * - 不能被捕获
     * - kill -9 强制杀死进程
     * - 不会执行清理代码
     *
     * SIGHUP (1):
     * - 终端关闭时发送
     * - 可用于配置重载
     */
    signal(SIGINT, signalHandler);
    signal(SIGTERM, signalHandler);

    // ========================================================================
    // 步骤3: 打印欢迎信息
    // ========================================================================

    /**
     * 【Banner设计】
     * 启动时显示版本信息，便于：
     * - 确认程序正确启动
     * - 排查版本问题
     * - 日志回溯
     *
     * 【生产改进】
     * - 添加构建时间、Git版本
     * - 添加编译选项（Debug/Release）
     * - JSON格式便于日志解析
     */
    std::cout << "========================================" << std::endl;
    std::cout << "     Lockstep Demo Server v1.0" << std::endl;
    std::cout << "========================================" << std::endl;

    // ========================================================================
    // 步骤4: 创建服务器实例
    // ========================================================================

    /**
     * 【栈上分配】
     * 服务器对象在栈上创建，生命周期由main管理
     * - 离开作用域自动析构
     * - 无需手动delete
     * - 无内存泄漏风险
     *
     * 【全局指针】
     * g_server指向栈对象，用于信号处理
     * 只在main返回前有效
     */
    lockstep::LockstepServer server(port);
    g_server = &server;

    // ========================================================================
    // 步骤5: 启动服务器
    // ========================================================================

    /**
     * 【启动检查】
     * start()失败的可能原因：
     * 1. 端口已被占用
     * 2. 网络初始化失败（Windows WSAStartup）
     * 3. 权限不足
     *
     * 【错误处理】
     * 启动失败返回1，便于脚本检测
     */
    if (!server.start()) {
        std::cerr << "[Server] Failed to start" << std::endl;
        return 1;
    }

    // 打印配置信息
    std::cout << "[Server] Logic FPS: " << lockstep::LockstepServer::LOGIC_FPS << std::endl;
    std::cout << "[Server] Max players: " << lockstep::LockstepServer::MAX_PLAYERS << std::endl;
    std::cout << "[Server] Press Ctrl+C to stop" << std::endl;
    std::cout << std::endl;

    // ========================================================================
    // 步骤6: 运行主循环
    // ========================================================================

    /**
     * 【阻塞调用】
     * run()是阻塞的，直到：
     * - 信号处理器调用stop()
     * - 内部错误退出
     *
     * 【程序流程】
     *
     *    main() ────> server.run() ──┐
     *                                │ [主循环运行中]
     *                                │
     *    SIGINT ────> handler() ─────┤
     *                    │           │
     *                    v           │
     *              stop() ───────────┘ [running_ = false]
     *                                │
     *                                v
     *    main() <──── return ────────┘
     */
    server.run();

    // ========================================================================
    // 步骤7: 清理退出
    // ========================================================================

    /**
     * 【析构顺序】
     * 1. 打印退出信息
     * 2. main返回，server离开作用域
     * 3. ~LockstepServer()调用stop()
     * 4. socket关闭，网络清理
     *
     * 【面试Q】g_server在main返回后是否安全？
     * A: main返回后server已析构，g_server成为悬空指针
     *    但此时进程即将退出，不会再访问
     *    严格来说应该设置g_server = nullptr
     */
    std::cout << "[Server] Stopped" << std::endl;
    return 0;
}

